	// phpcs:enable WordPress.WP.EnqueuedResources

	/**
	 * Renders the fixture page.
	 *
	 * Requires an active Brain Monkey session; the WordPress functions the
	 * renderer needs are stubbed here.
	 *
	 * @return string
	 */
	public static function render() {
		$timezone = new DateTimeZone( 'America/New_York' );
		$today    = new DateTimeImmutable( '2026-11-01 00:00:00', $timezone );

		self::stub_wordpress( $today );

		// Day anchors use a per-request counter; start it fresh so the
		// output does not depend on what rendered before.
		$counter = new ReflectionProperty( Memml_Renderer::class, 'month_instance' );
		$counter->setAccessible( true );
		$counter->setValue( null, 0 );

		$render = new ReflectionMethod( Memml_Renderer::class, 'render_month_calendar' );
		$render->setAccessible( true );

		$month = $render->invoke(
			new Memml_Renderer(),
			self::items(),
			'events',
			$timezone,
			array(
				'query_prefix' => 'memml_month_',
				'show_details' => true,
				'list_style'   => 'grid',
			)
		);

		return str_replace( '{{MONTH}}', $month, self::PAGE );
	}

	/**
	 * Feed items: a single event, a busy day with a multi-day event, a
	 * cancelled event, and a crowded day in the following month.
	 *
	 * @return array
	 */
	private static function items() {
		$items = array(
			array(
				'title'       => 'Library story time',
				'startsAt'    => '2026-11-03T15:00:00.000Z',
				'endsAt'      => '2026-11-03T16:00:00.000Z',
				'location'    => 'Main Library',
				'description' => 'Stories for kids.',
			),
			array(
				'title'    => 'Harvest weekend',
				'startsAt' => '2026-11-21T14:00:00.000Z',
				'endsAt'   => '2026-11-22T22:00:00.000Z',
				'location' => 'Town Green',
			),
			array(
				'title'    => 'Saturday fair',
				'startsAt' => '2026-11-21T15:00:00.000Z',
				'location' => 'Market Square',
			),
			array(
				'title'    => 'Book swap',
				'startsAt' => '2026-11-21T19:00:00.000Z',
				'status'   => 'cancelled',
				'location' => 'Main Library',
			),
		);

		foreach ( array( 'Winter concert', 'Choir rehearsal', 'Toy drive', 'Cookie swap' ) as $index => $title ) {
			$items[] = array(
				'title'    => $title,
				'startsAt' => sprintf( '2026-12-12T%02d:00:00.000Z', 15 + $index ),
				'location' => 'Town Hall',
			);
		}

		return $items;
	}

	/**
	 * Stubs the WordPress functions the month renderer calls.
	 *
	 * @param DateTimeImmutable $today Today in the organization timezone.
	 * @return void
	 */
	private static function stub_wordpress( $today ) {
		$escape = static function ( $text ) {
			return htmlspecialchars( (string) $text, ENT_QUOTES, 'UTF-8' );
		};

		Functions\when( '__' )->returnArg();
		Functions\when( 'esc_attr' )->alias( $escape );
		Functions\when( 'esc_html' )->alias( $escape );
		Functions\when( 'esc_attr__' )->alias( $escape );
		Functions\when( 'esc_html__' )->alias( $escape );
		Functions\when( 'esc_url' )->alias( $escape );
		Functions\when( 'sanitize_key' )->alias(
			static function ( $value ) {
				return strtolower( preg_replace( '/[^a-z0-9_-]/i', '', (string) $value ) );
			}
		);
		Functions\when( 'wp_unslash' )->returnArg();
		Functions\when( 'is_wp_error' )->alias(
			static function ( $value ) {
				return $value instanceof WP_Error;
			}
		);
		Functions\when( 'get_option' )->alias(
			static function ( $name, $default_value = false ) {
				$options = array(
					'date_format'   => 'F j, Y',
					'time_format'   => 'g:i A',
					'start_of_week' => 0,
				);

				return isset( $options[ $name ] ) ? $options[ $name ] : $default_value;
			}
		);
		Functions\when( 'wp_date' )->alias(
			static function ( $format, $timestamp, $timezone = null ) {
				$date = new DateTimeImmutable( '@' . $timestamp );

				return $date->setTimezone( $timezone ? $timezone : new DateTimeZone( 'UTC' ) )->format( $format );
			}
		);
		Functions\when( 'wp_parse_args' )->alias(
			static function ( $args, $defaults ) {
				return array_merge( $defaults, (array) $args );
			}
		);
		Functions\when( 'apply_filters' )->alias(
			static function ( $hook, $value ) use ( $today ) {
				return 'memml_calendar_today' === $hook ? $today : $value;
			}
		);
		Functions\when( '_n' )->alias(
			static function ( $single, $plural, $number ) {
				return 1 === $number ? $single : $plural;
			}
		);
		Functions\when( 'add_query_arg' )->alias(
			static function ( $arguments, $url = '' ) {
				$pairs = array();

				foreach ( $arguments as $name => $value ) {
					$pairs[] = $name . '=' . $value;
				}

				return $url . ( false === strpos( $url, '?' ) ? '?' : '&' ) . implode( '&', $pairs );
			}
		);
	}
}
