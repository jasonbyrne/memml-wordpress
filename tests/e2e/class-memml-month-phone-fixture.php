<?php
/**
 * Builds the phone Month browser-test fixture from real renderer output.
 *
 * @package Memml
 */

use Brain\Monkey\Functions;

/**
 * Renders tests/e2e/month-phone.html.
 *
 * The month markup comes from Memml_Renderer::render_month_calendar(), so the
 * browser tests exercise what visitors get. Regenerate the file with
 * `composer fixtures`; the unit suite fails when it is out of date.
 */
final class Memml_Month_Phone_Fixture {

	/**
	 * Fixture path.
	 */
	public const PATH = __DIR__ . '/month-phone.html';

	/**
	 * Page around the rendered month: a Month calendar with Month view on
	 * phones set to Keep Month and a List/Month switcher. It is a static test
	 * page, not WordPress output, so the stylesheet and script are linked
	 * directly.
	 */
	// phpcs:disable WordPress.WP.EnqueuedResources
	private const PAGE = <<<'HTML'
<!doctype html>
<html lang="en">
	<head>
		<meta charset="utf-8" />
		<meta name="viewport" content="width=device-width, initial-scale=1" />
		<title>Memml Calendar phone Month fixture</title>
		<link rel="stylesheet" href="/assets/calendar.css" />
	</head>
	<body>
		<!-- Generated by tests/e2e/generate-month-phone-fixture.php (composer fixtures). Do not edit by hand. -->
		<div class="memml-calendar memml-calendar--events" data-feed="events" data-layout="month" data-memml-calendar data-memml-url-prefix="memml_month_" data-period="upcoming">
			<div class="memml-calendar__toolbar">
				<div class="memml-calendar__filter memml-calendar__layout-filter" role="group" aria-label="Choose a display view"><a aria-controls="month-events-list" class="memml-calendar__filter-button" data-memml-layout="list" href="?memml_month_view=list">List</a><a aria-controls="month-events-month" aria-current="true" class="memml-calendar__filter-button" data-memml-layout="month" href="?memml_month_view=month">Month</a></div>
